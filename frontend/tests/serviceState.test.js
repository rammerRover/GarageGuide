test('uncertain removal cannot replay; subsequent 404 establishes only current absence', async () => {
  let reads = 0
  const f = await loaded('record', { getService: async () => ++reads === 1 ? success() : { kind: 'not-found', message: 'Service record not found.' },
    removeService: async () => ({ kind: 'uncertain' }) })
  f.store.requestRemoval(); await f.store.confirmRemoval()
  assert.equal(f.store.requestRemoval(), false)
  assert.equal((await f.store.confirmRemoval()).kind, 'cancelled')
  f.store.requestReload(); await f.store.reload()
  assert.match(f.store.getSnapshot().message, /currently absent.*does not establish/)
  assert.equal(f.calls.remove.length, 1)
  f.store.dispose()
})
for (const operation of ['create', 'update', 'remove']) test(`${operation}: synchronous in-flight guard prevents duplicate requests`, async () => {
  const reply = deferred(), mode = operation === 'create' ? 'history' : 'record'
  const f = await loaded(mode, { [`${operation}Service`]: () => reply.promise })
  if (operation === 'create') fill(f.store)
  if (operation === 'update') { f.store.beginEdit(); f.store.edit('notes', 'Draft') }
  if (operation === 'remove') f.store.requestRemoval()
  const action = () => operation === 'remove' ? f.store.confirmRemoval() : f.store.submit()
  const pending = action(); assert.equal((await action()).kind, 'cancelled')
  assert.equal(f.calls[operation].length, 1)
  reply.resolve(operation === 'remove' ? { kind: 'success', removed: { id: 8, vehicle_id: 7, deleted: true }, deadline: stamp() } : success())
  await pending; assert.equal(f.calls[operation].length, 1)
  f.store.dispose()
})
