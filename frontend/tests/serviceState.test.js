test('competing route IDs and superseded loads never publish old data or deadlines', async () => {
  const old = deferred()
  const f = await fixture('record', { getService: (v, id) => id === '8' ? old.promise : success({ id: Number(id), vehicle_id: Number(v) }) })
  const pending = f.store.load('7', '8'); await f.store.load('9', '10')
  old.resolve(success({}, stamp(60))); assert.equal((await pending).kind, 'cancelled')
  assert.equal(f.store.getSnapshot().record.id, 10)
  assert.equal(f.session.getSnapshot().expires_at, stamp())
  await f.store.load('01', '8'); assert.equal(f.store.getSnapshot().record, null)
  f.store.dispose()
})

test('navigation during the post-create GET cannot report a current success afterward', async () => {
  const reply = deferred()
  let reads = 0
  const f = await loaded('history', { listServices: () => ++reads === 1
    ? Promise.resolve({ kind: 'success', services: [], deadline: stamp() }) : reply.promise })
  fill(f.store)
  const pending = f.store.submit()
  // Wait for the confirmed create to hand off to its history reload.
  while (reads < 2) await Promise.resolve()
  f.store.depart()
  reply.resolve({ kind: 'success', services: [record], deadline: stamp(60) })
  assert.equal((await pending).kind, 'cancelled')
  assert.equal(f.store.getSnapshot().created, false)
  assert.deepEqual(f.store.getSnapshot().records, [])
  assert.equal(f.session.getSnapshot().expires_at, stamp())
  f.store.dispose()
})
